"""Answer cards (docs/UI_CARDS.md): the prompt section and the splitter that routes ONE openui-lang block out of the
model's text into 'ui' SSE events while the prose keeps streaming as 'token' events. The prompt text is generated by
`node tools/openui/gen_prompts.mjs` and committed as app/rag/ui_cards_prompt.txt (Python never needs Node).

Pure module: no import of app.chat. The splitter's output (token text, ui events, end.program) is identical for every
chunking of the same text; tests/test_ui_cards.py feeds every case whole, 1-, 3- and 7-char chunks to prove it."""
from __future__ import annotations

import logging
import re
from functools import lru_cache
from pathlib import Path

from app.config import settings

log = logging.getLogger("ui_cards")

PROMPT_FILE = Path(__file__).resolve().parent / "rag" / "ui_cards_prompt.txt"

FENCE_TAGS = ("```openui-lang\n", "```openui\n")        # opener forms, valid only at a line start (trailing [ \t]* before \n tolerated)
BARE_OPENER = "root = Card("                             # valid only at a line start and outside any other ``` fence
CLOSE_RE = re.compile(r"\n```[ \t]*(?:\n|\Z)")           # fenced close: ``` on its own line (or at stream end)
STMT_RE = re.compile(r"[A-Za-z_]\w{0,19} = ")            # "a statement line" for the bare-program close rule (decidable on 24 chars)
# Documented holdback bounds (docs/UI_CARDS.md), pinned by tests/test_ui_cards.py: the prose holdback is the longest
# proper prefix of an opener (len("```openui-lang") = 14, plus the newline run before it); the fenced holdback is a
# proper prefix of "\n```\n". _HOLD_CAP below bounds the trailing blanks a tag line may carry on top of these.
HOLD_PROSE = 15
HOLD_UI = 4

_OPEN_AT = re.compile("|".join(re.escape(t[:-1]) + r"[ \t]*\n" for t in FENCE_TAGS) + "|" + re.escape(BARE_OPENER))   # an opener, anchored by .match(buf, pos)
_CLOSE_FEED = re.compile(r"\n```[ \t]*\n")               # while streaming "\n```" at the buffer end is held, never closed (CLOSE_RE's \Z is for finish)
_EMPTY_CLOSE = re.compile(r"```[ \t]*(?:\n|\Z)")         # a fence closed on its very first line (empty program)
_STMT_DECIDE = 24                                        # STMT_RE needs at most 23 chars to match, so 24 decide a partial line
_HOLD_CAP = 64                                           # safety cap on any holdback (trailing spaces after a tag are unbounded in theory)


@lru_cache(maxsize=1)
def prompt_section() -> str:
    """The ANSWER CARD section appended last to the system prompt, or "" (with one warning) when the file is missing."""
    try:
        return "\n\n" + PROMPT_FILE.read_text("utf-8").strip() + "\n"
    except OSError as e:
        log.warning("answer cards disabled: %s unreadable (%s)", PROMPT_FILE, e)
        return ""


def wanted(cited: bool, booking: bool) -> bool:
    """Trigger policy: cards only on cited, non-booking answers (refusals, hand-over, custom and spend-cap paths never get here)."""
    return bool(settings.ui_cards_enabled and cited and not booking and prompt_section() != "")


def token(text: str) -> dict:
    return {"type": "token", "text": text}


def _line_starts(buf: str, line_start: bool):
    """Indexes in buf where a line begins (0 only when the buffer itself starts a line)."""
    if line_start:
        yield 0
    pos = buf.find("\n")
    while pos >= 0:
        yield pos + 1
        pos = buf.find("\n", pos + 1)


def _scan_lines(buf: str, line_start: bool, in_fence: bool = False):
    """Walk the line starts of buf: ((index, opener) or None, fence state at the end). An opener counts only outside an
    untagged / otherwise-tagged ``` fence (```json, ```python, bare ```), so a `root = Card(` quoted inside one stays
    prose; such a fence closes on ``` alone on a line. Never a regex ^ on a trimmed buffer."""
    fence = in_fence
    for i in _line_starts(buf, line_start):
        if buf.startswith("```", i):
            nl = buf.find("\n", i)
            core = (buf[i:] if nl < 0 else buf[i:nl]).rstrip(" \t")
            if fence:
                if core == "```":                        # the closing line of a generic fence (no info string)
                    fence = False
                continue
            m = _OPEN_AT.match(buf, i)
            if m and m.group(0).startswith("```"):
                return (i, m.group(0)), fence
            fence = True                                 # any other ``` line opens a generic fence
            continue
        if not fence:
            m = _OPEN_AT.match(buf, i)
            if m:
                return (i, m.group(0)), fence
    return None, fence


def _find_opener(buf: str, line_start: bool, in_fence: bool = False):
    """The earliest opener at a line start outside any other fence: (index, matched text) or None."""
    return _scan_lines(buf, line_start, in_fence)[0]


def has_block(text: str) -> bool:
    """True when the text carries an opener (fenced or bare) at a line start; custom answers without one keep the old
    single-token path byte for byte."""
    return _find_opener(text.replace("\r\n", "\n"), True) is not None


def _could_open(s: str) -> bool:
    """True if s (a line fragment with no newline) may still grow into an opener: a proper prefix of a fence tag line
    (trailing blanks tolerated after the tag) or of the bare opener."""
    if not s or len(s) > _HOLD_CAP:
        return False
    core = s.rstrip(" \t")
    if core and "```openui-lang".startswith(core):
        return True
    return s != BARE_OPENER and BARE_OPENER.startswith(s)


def _prose_hold(buf: str, line_start: bool) -> int:
    """Chars to hold at the end of a prose buffer: the longest line-start suffix that may become an opener plus the
    newline run before it (dropped from the prose if an opener follows); with no candidate, the trailing newline run."""
    tail = buf.rfind("\n") + 1  # the last line's start
    cand = 0
    for j in _line_starts(buf, line_start):
        if j >= tail and _could_open(buf[j:]):
            cand = len(buf) - j
            break
    core = buf[: len(buf) - cand].rstrip("\n")
    return len(buf) - len(core)


def _ui_hold(buf: str) -> int:
    """Chars to hold at the end of a fenced program: a proper prefix of "\\n```\\n" (blanks after ``` tolerated)."""
    for n in range(min(len(buf), _HOLD_CAP), 0, -1):
        s = buf[-n:]
        core = s.rstrip(" \t")
        if core and (core == "\n```" or ("\n```".startswith(core) and core == s)):
            return n
    return 0


class FenceSplitter:
    """Routes one openui-lang block out of a token stream. Modes: prose -> ui (fenced or bare) -> after; 'swallow'
    hides a second block or the rest of an over-long one. `stats` summarises the stream for logging."""

    def __init__(self, enabled: bool = True, max_chars: int = 4000):
        self.enabled, self.max_chars = enabled, max_chars
        self.mode, self.buf, self.program, self.bare = "prose", "", "", False
        self.line_start, self.held_cr, self.in_fence = True, False, False
        self.blocks, self.dropped = 0, 0
        self.stats = {"blocks": 0, "chars": 0, "complete": None, "reason": None, "dropped": 0}

    # ---------------------------------------------------------------- public
    def feed(self, chunk: str) -> list[dict]:
        if not self.enabled:
            return [token(chunk)] if chunk else []
        if self.held_cr:
            chunk, self.held_cr = "\r" + chunk, False
        if chunk.endswith("\r"):
            chunk, self.held_cr = chunk[:-1], True
        self.buf += chunk.replace("\r\n", "\n")
        out: list[dict] = []
        self._scan(out, finishing=False)
        return out

    def finish(self) -> list[dict]:
        if not self.enabled:
            return []
        if self.held_cr:
            self.buf, self.held_cr = self.buf + "\r", False
        out: list[dict] = []
        self._scan(out, finishing=True)
        if self.mode in ("prose", "after"):
            if self.buf:
                out.append(token(self.buf))
        elif self.mode == "ui" and not self.bare:
            m = CLOSE_RE.search(self.buf)
            if not self.program and _EMPTY_CLOSE.fullmatch(self.buf):
                self._close_fenced(out, 0)              # "```openui-lang\n```" with nothing in between
            elif m and m.end() == len(self.buf):        # buffer ends exactly on "\n```": a normal close
                self._close_fenced(out, m.start())
            else:                                       # max_tokens cut, provider error: partial program for logging only
                self._emit_body(out, self.buf)
                if self.mode == "ui":
                    out.append(self._end(complete=False, reason="unclosed"))
        elif self.mode == "ui":                         # bare program: it runs to the end of the stream
            self._emit_body(out, self.buf)
            if self.mode == "ui":
                out.append(self._end(complete=True))
        self.buf, self.mode = "", "prose"
        return out

    # ---------------------------------------------------------------- scanning
    def _scan(self, out: list[dict], finishing: bool) -> None:
        while True:
            if self.mode in ("prose", "after"):
                if not self._scan_prose(out):
                    return
            elif self.bare:
                if not self._scan_bare(out, finishing):
                    return
            else:
                if not self._scan_fenced(out):
                    return

    def _scan_prose(self, out: list[dict]) -> bool:
        """Prose passthrough with the opener holdback. Returns True when the mode changed (keep scanning)."""
        found = _find_opener(self.buf, self.line_start, self.in_fence)
        if found:
            i, opener = found
            before = self.buf[:i].rstrip("\n") if self.blocks == 0 else self.buf[:i]   # blank lines before the card go; later prose passes through
            if before:
                out.append(token(before))
            self.bare = not opener.startswith("```")
            self.buf = self.buf[i:] if self.bare else self.buf[i + len(opener):]   # the bare opener is code; a tag line is not
            self.line_start, self.in_fence = True, False                            # an opener is only found outside a generic fence
            if self.blocks >= 1:                       # at most one card per answer: the rest is dropped, never shown
                self.mode, self.dropped = "swallow", self.dropped + 1
                self.stats["dropped"] = self.dropped
            else:
                self.mode, self.blocks, self.program = "ui", 1, ""
                out.append({"type": "ui", "op": "start"})
            return True
        keep = _prose_hold(self.buf, self.line_start)
        if len(self.buf) > keep:
            text = self.buf[: len(self.buf) - keep]
            out.append(token(text))
            self.in_fence = _scan_lines(text, self.line_start, self.in_fence)[1]   # generic fences opened/closed by what just left
            self.buf, self.line_start = self.buf[len(self.buf) - keep:], text.endswith("\n")
        return False

    def _scan_fenced(self, out: list[dict]) -> bool:
        """Inside a fenced block (ui or swallow): close on ``` on its own line, else stream all but the holdback."""
        if not self.program:                            # an empty block closes on its first line
            m = _EMPTY_CLOSE.match(self.buf)
            if m:
                self._close_fenced(out, 0, m.end())
                return True
            if self.buf.rstrip(" \t") in ("`", "``", "```"):
                return False                            # may still become that close
        m = _CLOSE_FEED.search(self.buf)
        if m:
            self._close_fenced(out, m.start(), m.end())
            return True
        keep = _ui_hold(self.buf)
        if len(self.buf) > keep:
            body, self.buf = self.buf[: len(self.buf) - keep], self.buf[len(self.buf) - keep:]
            self._emit_body(out, body)
        return False

    def _scan_bare(self, out: list[dict], finishing: bool) -> bool:
        """Inside a bare program (ui or swallow): it ends at the first blank line followed by a non-statement line."""
        k = self.buf.find("\n\n")
        if k < 0:
            keep = 1 if self.buf.endswith("\n") else 0   # "\n" may become "\n\n"
            if len(self.buf) > keep:
                body, self.buf = self.buf[: len(self.buf) - keep], self.buf[len(self.buf) - keep:]
                self._emit_body(out, body)
            return False
        rest = self.buf[k + 2:]
        nl = rest.find("\n")
        line = rest if nl < 0 else rest[:nl]
        if nl < 0 and len(line) < _STMT_DECIDE and not finishing:
            if k:                                       # release what precedes the blank line, hold the rest
                self._emit_body(out, self.buf[:k])
                self.buf = self.buf[k:]
            return False
        if STMT_RE.match(line):                         # a blank line between statements: still the program
            n = k + 2 + len(line)
            self._emit_body(out, self.buf[:n])
            self.buf = self.buf[n:]
            return True
        self._emit_body(out, self.buf[:k])              # prose after the program: close, re-feed the held text as prose
        if self.mode == "ui":
            out.append(self._end(complete=True))
        self.mode, self.buf, self.line_start = "after", rest.lstrip("\n"), True
        return True

    # ---------------------------------------------------------------- emission
    def _close_fenced(self, out: list[dict], body_end: int, resume: int | None = None) -> None:
        self._emit_body(out, self.buf[:body_end])
        if self.mode == "ui":
            out.append(self._end(complete=True))
        self.buf = self.buf[resume:] if resume is not None else ""
        self.mode, self.line_start = "after", True

    def _emit_body(self, out: list[dict], body: str) -> None:
        """Append program text as a 'chunk'; past max_chars the block ends too_long and the rest is swallowed."""
        if not body or self.mode != "ui":
            return
        room = self.max_chars - len(self.program)
        if len(body) > room:
            body = body[:room]
            if body:
                self.program += body
                out.append({"type": "ui", "op": "chunk", "text": body})
            out.append(self._end(complete=False, reason="too_long"))
            self.mode = "swallow"
            return
        self.program += body
        out.append({"type": "ui", "op": "chunk", "text": body})

    def _end(self, complete: bool, reason: str | None = None) -> dict:
        prog = self.program.rstrip("\n")
        self.stats.update(blocks=self.blocks, chars=len(prog), complete=complete, reason=reason, dropped=self.dropped)
        if complete:
            return {"type": "ui", "op": "end", "program": prog, "complete": True}
        return {"type": "ui", "op": "end", "program": prog, "complete": False, "reason": reason or "unclosed"}


def split_text(text: str, enabled: bool = True, max_chars: int | None = None) -> list[dict]:
    """feed(text) + finish(): the event list for a whole answer (custom answers, tests)."""
    s = FenceSplitter(enabled=enabled, max_chars=max_chars if max_chars is not None else settings.ui_cards_max_chars)
    return s.feed(text) + s.finish()


def with_marker(text: str, marker: str) -> str:
    """Custom answers: the " [1]" marker goes on the prose, before the block when the answer carries one (so
    `answer + marker` stays byte-identical for every answer without a block)."""
    norm = text.replace("\r\n", "\n")
    found = _find_opener(norm, True)
    if not found or found[0] == 0:
        return text + marker
    head = norm[: found[0]]
    prose = head.rstrip("\n")
    return prose + marker + head[len(prose):] + norm[found[0]:]
